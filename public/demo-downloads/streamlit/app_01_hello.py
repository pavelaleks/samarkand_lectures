import re
from collections import Counter

import pandas as pd
import streamlit as st

st.set_page_config(page_title="Моё первое приложение", page_icon="📚", layout="wide")

# --- Заголовок и текст ---------------------------------------------------------
st.title("Моё первое приложение для филолога")
st.write("Streamlit превращает обычный код на Python в веб-страницу: каждое поле ввода — одна строка кода.")

# --- Поля ввода (виджеты) -----------------------------------------------------
text = st.text_area(
    "Вставьте фрагмент художественного текста",
    "Темнел московский серый зимний день, холодно зажигался газ в фонарях, тепло освещались витрины магазинов — "
    "и разгоралась вечерняя, освобождающаяся от дневных дел московская жизнь.",
    height=150,
)
top_n = st.slider("Сколько самых частых слов показать", min_value=5, max_value=30, value=10)
min_len = st.selectbox("Минимальная длина слова", [1, 3, 4, 5], index=1)

# --- Обработка (обычный Python) ----------------------------------------------
words = [w for w in re.findall(r"[а-яёa-z]+", text.lower()) if len(w) >= min_len]
freq = Counter(words).most_common(top_n)

# --- Вывод результатов --------------------------------------------------------
col1, col2 = st.columns(2)
col1.metric("Слов во фрагменте", len(words))
col2.metric("Разных слов", len(set(words)))

df = pd.DataFrame(freq, columns=["слово", "частота"])
st.subheader("Частотный список")
st.dataframe(df, use_container_width=True, hide_index=True)
st.bar_chart(df.set_index("слово"))

# --- Кнопка и скачивание -------------------------------------------------------
if st.button("Показать слова только из одного вхождения"):
    st.write(", ".join(sorted(w for w, c in Counter(words).items() if c == 1)))

st.download_button("⬇ Скачать таблицу (CSV для Excel)", df.to_csv(index=False).encode("utf-8-sig"), "chastoty.csv", "text/csv")

st.caption("Подсказка: справа сверху меню ⋮ → Rerun, если страница не обновилась после сохранения файла.")
