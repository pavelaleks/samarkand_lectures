# ШАГ 1. Самое маленькое приложение: заголовок, поле для текста, подсчёт слов.
# Каждая команда st.… — это один элемент на веб-странице.
import streamlit as st

st.title("Мой кабинет: тексты диссертации")                     # заголовок страницы
st.write("Вставьте фрагмент текста — я посчитаю слова.")          # обычный текст

text = st.text_area("Текст", "Темнел московский серый зимний день…", height=150)  # поле ввода

words = text.split()                                              # обычный Python: делим по пробелам
st.metric("Слов во фрагменте", len(words))                        # крупная цифра

