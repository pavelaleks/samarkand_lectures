def kwic_cell(default, var="texts"):
    return code(f"""
#@title 🔎 Проверка цитатой: слово в контексте (конкорданс) {{ display-mode: "form" }}
#@markdown Слова через запятую. Звёздочка = любое продолжение: `памят*`. Считается по леммам: `вспомнить` найдёт «вспомнила», «вспомню».
WORDS = "{default}"  #@param {{type:"string"}}
kwic({var}, WORDS, width=70, limit=25)
""")


def thesis_box(example, slide, limits):
    return md(f"""
### 🎓 Как это выглядит в диссертации
**Абзац для главы (образец — перепишите под себя):**
> {example}

**На защите — один слайд:** {slide}

**Когда метод врёт (впишите в «Ограничения»):** {limits}
""")


def note_cell(method, params, var="texts"):
    return code(f"""
#@title 📝 Черновик абзаца «Методология» (отредактируйте своими словами) {{ display-mode: "form" }}
method_note("{method}", {var}, {params})
""")


def submit(items):
    lis = "\n".join(f"- [ ] {x}" for x in items)
    return md(f"""
### ✅ Что сдать с пары
{lis}

Всё складывайте в свой **«Методологический паспорт диссертации»** (шаблон — на сайте курса, раздел «Применить к диссертации»).
""")


