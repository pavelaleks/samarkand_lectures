def md(text):
    return {"cell_type": "markdown", "metadata": {}, "source": text.strip("\n")}


def code(text, form=True):
    meta = {"cellView": "form"} if form else {}
    return {"cell_type": "code", "metadata": meta, "execution_count": None, "outputs": [], "source": text.strip("\n")}


def header(n, title, question, get, minutes="80–90 мин", track="Бунин · демо → ваш текст"):
    return md(f"""
# Пара {n}. {title}

| | |
|---|---|
| **Какой вопрос диссертации решает** | {question} |
| **Что вы получите** | {get} |
| **Трек** | {track} · {minutes} |

**Правило курса:** вопрос → процедура → картинка → **цитата** → ограничение. Число без цитаты в диссертацию не идёт.
""")


HOWTO = md("""
### Как работать (3 правила)
1. **Файл → Сохранить копию на Диске.** Иначе ваши правки пропадут.
2. Запускайте ячейки **по очереди сверху вниз** кнопкой ▶ слева от ячейки. Код спрятан — менять нужно **только поля формы** (справа в ячейке).
3. Сначала запустите всё **как есть** — это демо на Бунине, результат заведомо осмысленный. Потом в ячейке «Тексты» выберите **«Мои файлы»** и пройдите те же шаги на материале своей диссертации.

> Что-то сломалось? **Среда выполнения → Перезапустить сеанс**, затем ячейки сверху вниз.
> Красная ошибка — скопируйте **последние 3 строки** преподавателю или в бесплатный чат ИИ с вопросом «что это значит для новичка?».
> Свои файлы — **.txt (UTF-8) или .docx**. PDF и .doc сначала пересохраните.
""")

